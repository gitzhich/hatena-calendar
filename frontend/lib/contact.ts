/**
 * 削除要請・問い合わせの窓口（LR-05 / ADR-0017）。
 *
 * **掲載箇所はここだけを参照する。** 画面にアドレスを直接書かない。
 * 掲載箇所が増えるたびに書き換え漏れが起き、どれが正しいのか分からなくなる
 * （docs/coding-guidelines.md 第 11 章）。`lib/contact.test.ts` が検査する。
 *
 * **サイト専用のアドレスであること。** 運用者の個人アドレスを載せない。
 * 受信は個人の受信箱へ自動転送する。**誰も見ない窓口は無いのと同じ**で、
 * 削除要請の見落としが最悪の失敗になる（ADR-0017）。
 *
 * 難読化（画像化・JavaScript による組み立て）はしない。アクセシビリティを落とすうえ
 * 効果が限定的で、専用アドレスなのでスパムが来ても個人の受信箱は汚れない。
 */
